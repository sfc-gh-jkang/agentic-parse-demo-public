"""Generate sql/09b_agents.sql (both agents + Snowflake Intelligence registration) from one template.

Template blocks: @@app ... @@end (app agent only), @@si ... @@end (SI agent only), @@docs ... @@end (Snowflake
docs tool; dropped when docs=False), @@nodocs ... @@end (replacement text used only when docs=False),
everything else shared. The committed sql/09b_agents.sql is the docs=True rendering.
Usage: python3 scripts/gen_agents_sql.py [--check]
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TEMPLATE = ROOT / "sql" / "templates" / "agent_spec.yaml.tmpl"
OUT = ROOT / "sql" / "09b_agents.sql"
SI_OBJ = "SNOWFLAKE_INTELLIGENCE_OBJECT_DEFAULT"
FQ = "SNOWFLAKE_EXAMPLE.AGENTIC_PARSE_DEMO"

AGENTS = {
    "app": dict(
        name="AGENTIC_PARSE_DEMO_AGENT",
        comment="Agentic Parse Demo presenter agent: drives the whole app, explains it, search, re-parse, compare, cost, analytics",
        profile='{"display_name": "Agentic Parse Demo", "color": "blue"}',
    ),
    "si": dict(
        name="AGENTIC_PARSE_DEMO_SI_AGENT",
        comment="Agentic Parse Demo agent for Snowflake Intelligence: same tools as the app agent except control_app (no screen)",
        profile='{"display_name": "Agentic Parse Demo (Snowflake Intelligence)", "color": "blue"}',
    ),
}


def render(spec_tmpl: str, variant: str, docs: bool = True) -> str:
    out, keep = [], True
    for line in spec_tmpl.splitlines():
        if line.startswith("@@end"):
            keep = True
        elif line.startswith("@@"):
            tag = line.strip()[2:]
            keep = docs if tag == "docs" else (not docs) if tag == "nodocs" else tag == variant
        elif keep:
            out.append(line)
    return "\n".join(out) + "\n"


def snippet_block() -> str:
    """{{SNIPPETS}}: the Use this data snippets, from the one file the app shows and tests/test_use_data_snippets.py executes."""
    data = json.loads((ROOT / "web" / "lib" / "use-data-snippets.json").read_text())
    out = []
    for sn in data["snippets"]:
        sql = sn["sql"].replace("{doc}", "<doc_id>")
        run = {"read": "run in tests", "billed": "run in tests (billed AI call)", "pattern": "pattern, NOT run"}[sn["kind"]]
        out.append(f"    Snippet {sn['id']} ({sn['title']}; {run}; docs {data['doc_links'][sn['doc_link']]}):\n"
                   + "\n".join("      " + line for line in sql.splitlines()))
    return "\n".join(out)


def generate(docs: bool = True) -> str:
    tmpl = TEMPLATE.read_text().replace("{{SNIPPETS}}", snippet_block())
    parts = ["-- GENERATED by scripts/gen_agents_sql.py from sql/templates/agent_spec.yaml.tmpl. Do not edit; run the script.\n"
             "-- Run after 09_agent_tools.sql (procedures). The web app calls AGENTIC_PARSE_DEMO_AGENT (has control_app);\n"
             "-- only AGENTIC_PARSE_DEMO_SI_AGENT (no control_app, no screen) is registered in Snowflake Intelligence.\n"
             "USE ROLE AGENTIC_PARSE_DEMO_RL;\nUSE WAREHOUSE SFE_AGENTIC_PARSE_DEMO_WH;\nUSE SCHEMA SNOWFLAKE_EXAMPLE.AGENTIC_PARSE_DEMO;\n"]
    for v, a in AGENTS.items():
        parts.append(
            f"CREATE OR REPLACE AGENT {a['name']}\n  COMMENT = '{a['comment']}'\n  PROFILE = '{a['profile']}'\n"
            f"  FROM SPECIFICATION\n$$\n{render(tmpl, v, docs)}$$;\n")
    parts.append(f"""
-- Snowflake Intelligence: list ONLY the SI agent. Usage stays with the demo role (presenter-only); no PUBLIC grant.
USE ROLE ACCOUNTADMIN;
GRANT USAGE ON SNOWFLAKE INTELLIGENCE {SI_OBJ} TO ROLE AGENTIC_PARSE_DEMO_RL;
-- ADD AGENT fails with 400203 when already listed; that is fine on a re-run.
EXECUTE IMMEDIATE $$
BEGIN
  ALTER SNOWFLAKE INTELLIGENCE {SI_OBJ} ADD AGENT {FQ}.{AGENTS['si']['name']};
EXCEPTION
  WHEN STATEMENT_ERROR THEN
    IF (SQLCODE != 400203) THEN
      RAISE;
    END IF;
END;
$$;
-- The app agent must not appear in SI. DROP AGENT fails when it is not listed; that is fine on a re-run.
EXECUTE IMMEDIATE $$
BEGIN
  ALTER SNOWFLAKE INTELLIGENCE {SI_OBJ} DROP AGENT {FQ}.{AGENTS['app']['name']};
EXCEPTION
  WHEN STATEMENT_ERROR THEN
    NULL;
END;
$$;
""")
    return "\n".join(parts)


NO_DOCS_DIR = ROOT / "snowsight" / "no_docs"


def no_docs_text(name: str, text: str) -> str:
    """The text of sql/<name> for an account without the SNOWFLAKE_DOCUMENTATION database (names untouched)."""
    if name == "09b_agents.sql":
        return generate(docs=False)
    if name == "01_setup.sql":
        out = [l for l in text.splitlines(keepends=True)
               if "SNOWFLAKE_DOCUMENTATION" not in l and "CKE_SNOWFLAKE_DOCS_SERVICE lives" not in l]
        return "".join(out)
    raise ValueError(name)


def no_docs_install(install: str) -> str:
    """snowsight/install.sql pointing at the no-docs copies of 01_setup.sql and 09b_agents.sql."""
    base = "@SNOWFLAKE_EXAMPLE.PUBLIC.AGENTIC_PARSE_DEMO_REPO/branches/main/"
    out = install
    for f in ("01_setup.sql", "09b_agents.sql"):
        assert f"{base}sql/{f}" in out
        out = out.replace(f"{base}sql/{f}", f"{base}snowsight/no_docs/{f}")
    out = out.replace("-- Needs ACCOUNTADMIN and the 'Snowflake Documentation' Cortex Knowledge Extension (database SNOWFLAKE_DOCUMENTATION).",
                      "-- NO-DOCS variant: for accounts without the 'Snowflake Documentation' database (SNOWFLAKE_DOCUMENTATION). The agents get no\n"
                      "-- snowflake_docs tool. GENERATED by scripts/gen_agents_sql.py from snowsight/install.sql; do not edit. Needs ACCOUNTADMIN.")
    return out


def variants() -> dict:
    setup = (ROOT / "sql" / "01_setup.sql").read_text()
    return {
        NO_DOCS_DIR / "01_setup.sql": no_docs_text("01_setup.sql", setup),
        NO_DOCS_DIR / "09b_agents.sql": generate(docs=False),
        ROOT / "snowsight" / "install_no_docs.sql": no_docs_install((ROOT / "snowsight" / "install.sql").read_text()),
    }


if __name__ == "__main__":
    text = generate()
    files = {OUT: text, **variants()}
    if "--check" in sys.argv:
        sys.exit(0 if all(f.exists() and f.read_text() == t for f, t in files.items()) else 1)
    for f, t in files.items():
        f.parent.mkdir(parents=True, exist_ok=True)
        f.write_text(t)
        print(f"wrote {f}")
