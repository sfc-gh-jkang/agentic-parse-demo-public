-- Agentic Parse Demo: role, namespace, warehouse, stage.
-- Pattern matches SNOWFLAKE_EXAMPLE.SIGMA_WRITEBACK: ACCOUNTADMIN creates the
-- schema and hands ownership to a dedicated least-privilege demo role.
USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS AGENTIC_PARSE_DEMO_RL COMMENT = 'Agentic Parse Demo app, agent and pipeline';
GRANT ROLE AGENTIC_PARSE_DEMO_RL TO ROLE SYSADMIN;
-- No session variable: EXECUTE IMMEDIATE FROM (snowsight/install.sql) rejects them.
EXECUTE IMMEDIATE $$
BEGIN
  LET stmt STRING := 'GRANT ROLE AGENTIC_PARSE_DEMO_RL TO USER "' || CURRENT_USER() || '"';
  EXECUTE IMMEDIATE :stmt;
END;
$$;
-- Required for AI_PARSE_DOCUMENT and other Cortex AI functions.
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE AGENTIC_PARSE_DEMO_RL;
-- Read ACCOUNT_USAGE.CORTEX_AI_FUNCTIONS_USAGE_HISTORY for measured cost (PARSE_COST).
GRANT DATABASE ROLE SNOWFLAKE.USAGE_VIEWER TO ROLE AGENTIC_PARSE_DEMO_RL;

CREATE WAREHOUSE IF NOT EXISTS SFE_AGENTIC_PARSE_DEMO_WH
  WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
  COMMENT = 'Agentic Parse Demo';
GRANT USAGE, OPERATE ON WAREHOUSE SFE_AGENTIC_PARSE_DEMO_WH TO ROLE AGENTIC_PARSE_DEMO_RL;

CREATE DATABASE IF NOT EXISTS SNOWFLAKE_EXAMPLE COMMENT = 'Snowflake demo projects';
CREATE SCHEMA IF NOT EXISTS SNOWFLAKE_EXAMPLE.AGENTIC_PARSE_DEMO COMMENT = 'Agentic Parse Demo';
GRANT USAGE ON DATABASE SNOWFLAKE_EXAMPLE TO ROLE AGENTIC_PARSE_DEMO_RL;
GRANT OWNERSHIP ON SCHEMA SNOWFLAKE_EXAMPLE.AGENTIC_PARSE_DEMO TO ROLE AGENTIC_PARSE_DEMO_RL COPY CURRENT GRANTS;


USE ROLE AGENTIC_PARSE_DEMO_RL;
USE SCHEMA SNOWFLAKE_EXAMPLE.AGENTIC_PARSE_DEMO;

-- AI_PARSE_DOCUMENT needs server-side encryption on internal stages.
CREATE STAGE IF NOT EXISTS DOCS
  ENCRYPTION = (TYPE = 'SNOWFLAKE_SSE')
  DIRECTORY = (ENABLE = TRUE)
  COMMENT = 'Corpus and Uploaded Documents';

CREATE STAGE IF NOT EXISTS CODE COMMENT = 'Python modules imported by procedures';
